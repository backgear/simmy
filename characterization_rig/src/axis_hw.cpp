#include <Arduino.h>
#include "axis_hw.h"
#include "run_buffer.h"

/* ===========================================================================
 * Hardware notes (Blue Pill / STM32F103C8T6, medium-density F1):
 *
 *  - No on-chip DAC exists on this part. Rather than simply not offering
 *    analog output, OUTPUT_ANALOG_PWM_RC drives TIM3 CH1/CH2
 *    (PIN_PWM_POS/PIN_PWM_NEG, i.e. PA6/PA7) as a 32kHz "poor-man's DAC":
 *    the same RC-filtered-PWM approach, the same pin choice, and the
 *    same bipolar-as-two-unipolar-channels encoding as the sibling
 *    ~/analog-servo-f103 firmware's Output.c/tim_f1.c for this same
 *    part -- see analog_pwm_write() below. It still needs an external
 *    RC low-pass per channel plus a downstream differential-input
 *    stage; this firmware only produces the two PWM signals.
 *  - TIM2/TIM4 are reserved entirely for hardware quadrature decode
 *    (TI12 mode, i.e. x4) on their default, non-remapped CH1/CH2 pins;
 *    TIM3's CH1/CH2 pins go to PWM output instead (see above), so this
 *    board supports 2 encoders, not the protocol's general "up to 4".
 *    x4 is this firmware's only supported decode multiplier; a manifest
 *    asking for x1/x2 is UNSUPPORTED rather than silently promoted.
 *  - TIM1 (via the Arduino HardwareTimer wrapper) is the only timer not
 *    tied to a GPIO function here: it just drives a fixed-rate service
 *    ISR that is the device's whole real-time engine (tick counter, step
 *    edge scheduling, capture latching, watchdog/estop/travel-limit
 *    checks). See TICKS_PER_SERVICE in axis_config.h for the declared
 *    quantization/timing-error bound this implies.
 *  - Step/dir timing is generated by evenly spacing edges within each
 *    command interval via integer (Bresenham-style) accumulation, exactly
 *    as the protocol specifies, *provided* SEAL rejected any interval
 *    whose required edge rate would need more than one edge per service
 *    tick (see protocol.cpp's SEAL handler) -- that keeps this ISR O(1)
 *    per tick with no catch-up loops.
 *  - Direction setup/hold is honored by holding off the first edge of an
 *    interval until dir_setup_ticks + dir_hold_ticks after the interval
 *    boundary whenever direction changes; the DIR pin itself flips at the
 *    boundary. This is a conservative, not maximally tight, scheduling
 *    choice -- documented here rather than silently assumed perfect.
 * ==========================================================================
 */

static volatile uint64_t g_tick = 0;
static HardwareTimer *g_service_timer = nullptr;

static run_config_t g_cfg;
static bool g_cfg_valid = false;

typedef enum { HW_IDLE, HW_ARMED, HW_RUNNING, HW_DONE, HW_FAULT } hw_phase_t;
static volatile hw_phase_t g_phase = HW_IDLE;
static volatile fault_reason_t g_fault_reason = FAULT_NONE;
static volatile uint64_t g_fault_tick = 0;

/* ---- encoder extension state ---- */
static TIM_HandleTypeDef s_enc_htim[NUM_ENCODERS];
static TIM_TypeDef *const s_enc_TIMx[NUM_ENCODERS] = { TIM2, TIM4 };
static volatile int64_t s_enc_ext[NUM_ENCODERS];
static uint16_t s_enc_last16[NUM_ENCODERS];
static int64_t s_enc_origin[NUM_ENCODERS];

/* ---- analog (PWM "poor-man's DAC") output state ---- */
static TIM_HandleTypeDef s_pwm_htim3;
static bool s_pwm_started = false;

/* ---- run schedule state ---- */
static uint64_t g_command_start_tick, g_capture_start_tick, g_run_end_tick;
static uint32_t g_cur_interval = 0xFFFFFFFFu;
static int32_t g_prev_cum = 0;
static int32_t g_transitions_total = 0;
static int32_t g_transitions_emitted = 0;
static bool g_direction_positive = true;
static bool g_have_prev_direction = false;
static uint32_t g_min_first_edge_rel = 0;
static bool g_step_pin_high = false;
static uint64_t g_step_low_at_tick = 0;
static bool g_quad_state = false; /* 2-bit gray code index 0..3, packed as two bools below */
static uint8_t g_quad_index = 0;

static uint64_t g_next_capture_tick[NUM_CAPTURE_STREAMS];
static uint64_t g_watchdog_deadline = 0;

static inline void write_step_dir_idle(void) {
    digitalWrite(PIN_STEP, g_cfg_valid && g_cfg.output_idle_level_high ? HIGH : LOW);
    digitalWrite(PIN_DIR, LOW);
}
static void analog_pwm_write(int32_t code); /* defined below, used by axis_hw_set_idle_outputs */

void axis_hw_set_idle_outputs(void) {
    if (g_cfg_valid && g_cfg.output_mode == OUTPUT_ANALOG_PWM_RC) {
        if (s_pwm_started) analog_pwm_write(0);
    } else {
        pinMode(PIN_STEP, OUTPUT);
        pinMode(PIN_DIR, OUTPUT);
        write_step_dir_idle();
        g_step_pin_high = false;
        g_quad_index = 0;
    }
    pinMode(PIN_ENABLE, OUTPUT);
    /* Safe/idle = drive disabled until an ARM explicitly enables it. */
    digitalWrite(PIN_ENABLE, g_cfg_valid && g_cfg.enable_active_high ? LOW : HIGH);
}

bool axis_hw_estop_asserted(void) {
    return digitalRead(PIN_ESTOP) == LOW;
}

/* TIM3 CH1 (PIN_PWM_POS) / CH2 (PIN_PWM_NEG), PSC=0 ARR=TIM3_PWM_ARR ->
 * 72MHz/(ARR+1) = 32kHz carrier. Matches ~/analog-servo-f103's tim_f1.c
 * Tim3PwmInit() exactly (same part, same timer, same pins). */
static void pwm_begin(void) {
    __HAL_RCC_TIM3_CLK_ENABLE();
    __HAL_RCC_GPIOA_CLK_ENABLE();

    GPIO_InitTypeDef gpio = {0};
    gpio.Mode = GPIO_MODE_AF_PP;
    gpio.Speed = GPIO_SPEED_FREQ_HIGH;
    gpio.Pin = GPIO_PIN_6 | GPIO_PIN_7;
    HAL_GPIO_Init(GPIOA, &gpio);

    s_pwm_htim3.Instance = TIM3;
    s_pwm_htim3.Init.Prescaler = 0;
    s_pwm_htim3.Init.CounterMode = TIM_COUNTERMODE_UP;
    s_pwm_htim3.Init.Period = TIM3_PWM_ARR;
    s_pwm_htim3.Init.ClockDivision = TIM_CLOCKDIVISION_DIV1;
    s_pwm_htim3.Init.AutoReloadPreload = TIM_AUTORELOAD_PRELOAD_DISABLE;
    HAL_TIM_PWM_Init(&s_pwm_htim3);

    TIM_OC_InitTypeDef oc = {0};
    oc.OCMode = TIM_OCMODE_PWM1;
    oc.Pulse = 0;
    oc.OCPolarity = TIM_OCPOLARITY_HIGH;
    oc.OCFastMode = TIM_OCFAST_DISABLE;
    HAL_TIM_PWM_ConfigChannel(&s_pwm_htim3, &oc, TIM_CHANNEL_1);
    HAL_TIM_PWM_ConfigChannel(&s_pwm_htim3, &oc, TIM_CHANNEL_2);
    HAL_TIM_PWM_Start(&s_pwm_htim3, TIM_CHANNEL_1);
    HAL_TIM_PWM_Start(&s_pwm_htim3, TIM_CHANNEL_2);
}

/* Bipolar code -> two unipolar PWM duties (OutputSplit() in
 * ~/analog-servo-f103's Output.c): whichever channel matches the
 * commanded sign carries the magnitude, 0..TIM3_PWM_ARR; the other
 * channel sits at its own zero. A downstream differential-input stage
 * recovers the bipolar result, so "zero" is both channels at 0, not
 * both at mid-scale. */
static void analog_pwm_write(int32_t code) {
    int32_t full_scale = g_cfg_valid && g_cfg.analog_output_full_scale > 0
        ? g_cfg.analog_output_full_scale : 32767;
    int32_t max = (int32_t)TIM3_PWM_ARR;
    int32_t raw = (int32_t)(((int64_t)code * max) / full_scale);
    if (raw < -max) raw = -max;
    if (raw > max) raw = max;
    uint32_t pos = (raw >= 0) ? (uint32_t)raw : 0u;
    uint32_t neg = (raw < 0) ? (uint32_t)(-raw) : 0u;
    __HAL_TIM_SET_COMPARE(&s_pwm_htim3, TIM_CHANNEL_1, pos);
    __HAL_TIM_SET_COMPARE(&s_pwm_htim3, TIM_CHANNEL_2, neg);
}

static void enc_poll_extend(uint32_t i) {
    uint16_t now16 = (uint16_t)__HAL_TIM_GET_COUNTER(&s_enc_htim[i]);
    int16_t delta = (int16_t)(now16 - s_enc_last16[i]); /* wraps correctly for +/-32767 per poll */
    s_enc_ext[i] += delta;
    s_enc_last16[i] = now16;
}

static void service_isr(void) {
    g_tick += TICKS_PER_SERVICE;

    /* Encoder extension runs continuously, independent of run phase --
     * "Encoders are counted continuously in hardware...not by sampling
     * A/B at the acquisition frequency." */
    for (uint32_t i = 0; i < NUM_ENCODERS; i++) {
        if (g_cfg_valid && g_cfg.encoder_enabled[i]) enc_poll_extend(i);
    }

    if (g_phase == HW_ARMED) {
        if (g_cfg.connection_policy == CONN_SUPERVISED && g_tick > g_watchdog_deadline) {
            g_phase = HW_FAULT;
            g_fault_reason = FAULT_WATCHDOG;
            g_fault_tick = g_tick;
            axis_hw_set_idle_outputs();
            return;
        }
        if (axis_hw_estop_asserted()) {
            g_phase = HW_FAULT;
            g_fault_reason = FAULT_ESTOP;
            g_fault_tick = g_tick;
            axis_hw_set_idle_outputs();
        }
        return;
    }

    if (g_phase != HW_RUNNING) return;

    if (g_cfg.connection_policy == CONN_SUPERVISED && g_tick > g_watchdog_deadline) {
        g_phase = HW_FAULT; g_fault_reason = FAULT_WATCHDOG; g_fault_tick = g_tick;
        axis_hw_set_idle_outputs();
        return;
    }
    if (axis_hw_estop_asserted()) {
        g_phase = HW_FAULT; g_fault_reason = FAULT_ESTOP; g_fault_tick = g_tick;
        axis_hw_set_idle_outputs();
        return;
    }
    for (uint32_t i = 0; i < NUM_ENCODERS; i++) {
        if (!g_cfg.encoder_enabled[i] || !g_cfg.travel_limit_enabled[i]) continue;
        int64_t rel = s_enc_ext[i] - s_enc_origin[i];
        int64_t lim = g_cfg.travel_limit_counts[i];
        if (rel > lim || rel < -lim) {
            g_phase = HW_FAULT; g_fault_reason = FAULT_INTERLOCK; g_fault_tick = g_tick;
            axis_hw_set_idle_outputs();
            return;
        }
    }

    /* Drop a pending step pulse low once its declared width has elapsed. */
    if (g_step_pin_high && g_tick >= g_step_low_at_tick) {
        digitalWrite(PIN_STEP, g_cfg.output_idle_level_high ? HIGH : LOW);
        g_step_pin_high = false;
    }

    /* ---- capture ---- */
    bool any_active_stream = false;
    for (uint32_t s = 0; s < NUM_CAPTURE_STREAMS; s++) {
        capture_stream_t *cs = capstream_instance(s);
        bool enabled = (s < NUM_ENCODERS) ? g_cfg.encoder_enabled[s] : g_cfg.analog_enabled;
        if (!enabled || cs->capacity == 0) continue;
        any_active_stream = true;
        if (g_tick >= g_next_capture_tick[s]) {
            if (s < NUM_ENCODERS) {
                int32_t v = (int32_t)s_enc_ext[s];
                capstream_append(cs, &v);
            } else {
                int32_t vals[NUM_ANALOG_CHANNELS];
                vals[0] = analogRead(PIN_ANALOG0);
                if (NUM_ANALOG_CHANNELS > 1) vals[1] = analogRead(PIN_ANALOG1);
                capstream_append(cs, vals);
            }
            g_next_capture_tick[s] += cs->period_ticks;
        }
    }
    (void)any_active_stream;

    /* ---- command / step generation ---- */
    if (g_tick >= g_command_start_tick) {
        uint64_t elapsed = g_tick - g_command_start_tick;
        uint32_t interval = (uint32_t)(elapsed / g_cfg.command_period_ticks);

        if (interval < g_cfg.command_sample_count && g_cfg.output_mode == OUTPUT_ANALOG_PWM_RC) {
            /* Zero-order hold applied at the interval's start: the
             * sample itself is the held code, not a cumulative count --
             * no edges, no direction pin, nothing to do mid-interval. */
            if (interval != g_cur_interval) {
                g_cur_interval = interval;
                analog_pwm_write(cmdbuf_value_at(cmdbuf_instance(), interval));
            }
        } else if (interval < g_cfg.command_sample_count) {
            if (interval != g_cur_interval) {
                g_cur_interval = interval;
                command_buffer_t *cb = cmdbuf_instance();
                g_prev_cum = (interval == 0) ? 0 : cmdbuf_value_at(cb, interval - 1);
                int32_t target = cmdbuf_value_at(cb, interval);
                g_transitions_total = target - g_prev_cum;
                g_transitions_emitted = 0;
                bool new_dir = (g_transitions_total >= 0);
                bool dir_changed = g_have_prev_direction && (new_dir != g_direction_positive);
                g_direction_positive = new_dir;
                g_have_prev_direction = true;
                if (g_cfg.output_mode == OUTPUT_STEP_DIR) {
                    digitalWrite(PIN_DIR, g_direction_positive ? HIGH : LOW);
                }
                g_min_first_edge_rel = dir_changed
                    ? (g_cfg.dir_setup_ticks + g_cfg.dir_hold_ticks)
                    : 0;
            }

            if (g_transitions_total != 0) {
                uint32_t n_abs = (uint32_t)((g_transitions_total < 0) ? -g_transitions_total : g_transitions_total);
                uint64_t elapsed_in_interval = elapsed - (uint64_t)interval * g_cfg.command_period_ticks;
                uint32_t k_target = (uint32_t)((elapsed_in_interval * n_abs) / g_cfg.command_period_ticks);
                if (k_target > n_abs) k_target = n_abs;
                if ((int32_t)k_target > g_transitions_emitted) {
                    bool gated = (g_transitions_emitted == 0) && (elapsed_in_interval < g_min_first_edge_rel);
                    if (!gated) {
                        g_transitions_emitted++;
                        if (g_cfg.output_mode == OUTPUT_STEP_DIR) {
                            digitalWrite(PIN_STEP, g_cfg.output_idle_level_high ? LOW : HIGH);
                            g_step_pin_high = true;
                            g_step_low_at_tick = g_tick + g_cfg.step_pulse_width_ticks;
                        } else { /* quadrature command: one Gray-code step per transition */
                            g_quad_index = (uint8_t)((g_quad_index + (g_direction_positive ? 1 : 3)) & 0x3);
                            static const uint8_t gray_a[4] = {0, 0, 1, 1};
                            static const uint8_t gray_b[4] = {0, 1, 1, 0};
                            uint8_t idx = g_cfg.quadrature_invert ? (uint8_t)(3 - g_quad_index) : g_quad_index;
                            digitalWrite(PIN_STEP, gray_a[idx] ? HIGH : LOW);
                            digitalWrite(PIN_DIR, gray_b[idx] ? HIGH : LOW);
                        }
                    }
                }
            }
        }
    }

    if (g_tick >= g_run_end_tick) {
        g_phase = HW_DONE;
    }
}

void axis_hw_init(void) {
    pinMode(PIN_ESTOP, INPUT_PULLUP);
    analogReadResolution(12);

    axis_hw_set_idle_outputs();

    for (uint32_t i = 0; i < NUM_ENCODERS; i++) {
        s_enc_ext[i] = 0;
        s_enc_last16[i] = 0;
        s_enc_origin[i] = 0;
    }

    g_service_timer = new HardwareTimer(TIM1);
    g_service_timer->setOverflow((uint32_t)(TICK_HZ / TICKS_PER_SERVICE), HERTZ_FORMAT);
    g_service_timer->attachInterrupt(service_isr);
    g_service_timer->resume();
}

uint64_t axis_hw_now_ticks(void) {
    noInterrupts();
    uint64_t t = g_tick;
    interrupts();
    return t;
}

static bool encoder_timer_begin(uint32_t i) {
    TIM_HandleTypeDef *h = &s_enc_htim[i];
    h->Instance = s_enc_TIMx[i];
    h->Init.Prescaler = 0;
    h->Init.CounterMode = TIM_COUNTERMODE_UP;
    h->Init.Period = 0xFFFF;
    h->Init.ClockDivision = TIM_CLOCKDIVISION_DIV1;
    h->Init.RepetitionCounter = 0;

    TIM_Encoder_InitTypeDef enc;
    enc.EncoderMode = TIM_ENCODERMODE_TI12; /* x4 decode: this firmware's only supported mode */
    enc.IC1Polarity = TIM_ICPOLARITY_RISING;
    enc.IC1Selection = TIM_ICSELECTION_DIRECTTI;
    enc.IC1Prescaler = TIM_ICPSC_DIV1;
    enc.IC1Filter = 6;
    enc.IC2Polarity = TIM_ICPOLARITY_RISING;
    enc.IC2Selection = TIM_ICSELECTION_DIRECTTI;
    enc.IC2Prescaler = TIM_ICPSC_DIV1;
    enc.IC2Filter = 6;

    if (s_enc_TIMx[i] == TIM2) { __HAL_RCC_TIM2_CLK_ENABLE(); __HAL_RCC_GPIOA_CLK_ENABLE(); }
    else { __HAL_RCC_TIM4_CLK_ENABLE(); __HAL_RCC_GPIOB_CLK_ENABLE(); }

    GPIO_InitTypeDef gpio = {0};
    gpio.Mode = GPIO_MODE_INPUT;
    gpio.Pull = GPIO_PULLUP;
    if (s_enc_TIMx[i] == TIM2) {
        gpio.Pin = GPIO_PIN_0 | GPIO_PIN_1;
        HAL_GPIO_Init(GPIOA, &gpio);
    } else {
        gpio.Pin = GPIO_PIN_6 | GPIO_PIN_7;
        HAL_GPIO_Init(GPIOB, &gpio);
    }

    if (HAL_TIM_Encoder_Init(h, &enc) != HAL_OK) return false;
    if (HAL_TIM_Encoder_Start(h, TIM_CHANNEL_ALL) != HAL_OK) return false;
    return true;
}

const char *axis_hw_validate_config(const run_config_t *cfg) {
    if (cfg->command_sample_count == 0 || cfg->command_sample_count > MAX_COMMAND_SAMPLES) return "RANGE";
    if (cfg->command_period_ticks < TICKS_PER_SERVICE) return "LIMIT"; /* can't resolve finer than our service tick */
    bool any_encoder = false;
    for (uint32_t i = 0; i < NUM_ENCODERS; i++) {
        if (!cfg->encoder_enabled[i]) continue;
        any_encoder = true;
        if (cfg->encoder_decode_mult[i] != 4) return "UNSUPPORTED";
    }
    if (any_encoder && cfg->encoder_sample_period_ticks < TICKS_PER_SERVICE) return "LIMIT";
    if (cfg->analog_enabled && cfg->analog_sample_period_ticks < 50u * TICKS_PER_SERVICE) return "LIMIT";
    if (cfg->output_mode == OUTPUT_ANALOG_PWM_RC) {
        if (cfg->analog_output_full_scale <= 0) return "RANGE";
    } else {
        if (cfg->step_pulse_width_ticks == 0) return "RANGE";
        if (cfg->step_pulse_width_ticks * 2 >= cfg->command_period_ticks) return "LIMIT";
    }
    return nullptr;
}

void axis_hw_configure(const run_config_t *cfg) {
    g_cfg = *cfg;
    g_cfg_valid = true;

    static bool encoders_started[NUM_ENCODERS];
    for (uint32_t i = 0; i < NUM_ENCODERS; i++) {
        if (cfg->encoder_enabled[i] && !encoders_started[i]) {
            encoder_timer_begin(i);
            encoders_started[i] = true;
        }
    }

    if (cfg->output_mode == OUTPUT_QUADRATURE_COMMAND) {
        pinMode(PIN_STEP, OUTPUT); /* reused as quadrature A */
        pinMode(PIN_DIR, OUTPUT);  /* reused as quadrature B */
    } else if (cfg->output_mode == OUTPUT_ANALOG_PWM_RC && !s_pwm_started) {
        pwm_begin();
        s_pwm_started = true;
    }
    axis_hw_set_idle_outputs();
}

void axis_hw_latch_origin(void) {
    for (uint32_t i = 0; i < NUM_ENCODERS; i++) {
        enc_poll_extend(i);
        s_enc_origin[i] = s_enc_ext[i];
    }
    g_phase = HW_ARMED;
    g_fault_reason = FAULT_NONE;
    pinMode(PIN_ENABLE, OUTPUT);
    digitalWrite(PIN_ENABLE, g_cfg.enable_active_high ? HIGH : LOW);
}

void axis_hw_schedule_start(uint64_t command_start_tick, uint64_t capture_start_tick) {
    g_command_start_tick = command_start_tick;
    g_capture_start_tick = capture_start_tick;
    g_run_end_tick = command_start_tick
        + (uint64_t)g_cfg.command_sample_count * g_cfg.command_period_ticks
        + g_cfg.capture_post_roll_ticks;
    g_cur_interval = 0xFFFFFFFFu;
    g_have_prev_direction = false;
    g_transitions_total = 0;
    g_transitions_emitted = 0;

    for (uint32_t s = 0; s < NUM_CAPTURE_STREAMS; s++) {
        capture_stream_t *cs = capstream_instance(s);
        cs->first_sample_tick = capture_start_tick;
        g_next_capture_tick[s] = capture_start_tick;
    }

    g_phase = HW_RUNNING;
}

void axis_hw_abort(fault_reason_t reason) {
    noInterrupts();
    g_phase = HW_FAULT;
    g_fault_reason = reason;
    g_fault_tick = g_tick;
    interrupts();
    axis_hw_set_idle_outputs();
}

void axis_hw_feed_watchdog(void) {
    noInterrupts();
    g_watchdog_deadline = g_tick + g_cfg.watchdog_timeout_ticks;
    interrupts();
}

void axis_hw_get_status(axis_status_t *out) {
    noInterrupts();
    hw_phase_t phase = g_phase;
    fault_reason_t reason = g_fault_reason;
    uint64_t ftick = g_fault_tick;
    uint32_t idx = g_cur_interval;
    uint64_t end_tick = g_run_end_tick;
    bool step_high = g_step_pin_high;
    interrupts();

    out->running = (phase == HW_RUNNING);
    out->armed = (phase == HW_ARMED);
    out->complete = (phase == HW_DONE);
    out->fault = (phase == HW_FAULT);
    out->fault_reason = reason;
    out->fault_tick = ftick;
    out->executed_command_index = (idx == 0xFFFFFFFFu) ? 0 : idx;
    out->output_enabled = g_cfg_valid &&
        (digitalRead(PIN_ENABLE) == (g_cfg.enable_active_high ? HIGH : LOW));
    out->command_start_tick = g_command_start_tick;
    out->capture_start_tick = g_capture_start_tick;
    out->run_end_tick = end_tick;
    (void)step_high;

    bool complete = true;
    for (uint32_t s = 0; s < NUM_CAPTURE_STREAMS; s++) {
        capture_stream_t *cs = capstream_instance(s);
        out->captured_count[s] = cs->count;
        bool enabled = (s < NUM_ENCODERS) ? (g_cfg_valid && g_cfg.encoder_enabled[s])
                                           : (g_cfg_valid && g_cfg.analog_enabled);
        if (cs->overflowed) complete = false;
        if (enabled && !(phase == HW_DONE || phase == HW_FAULT)) complete = false;
    }
    out->capture_complete = complete && (phase == HW_DONE || phase == HW_FAULT);
}

void *axis_hw_capture_stream(uint32_t stream_id) {
    return capstream_instance(stream_id);
}
